  const LOCALES = Object.keys(MESSAGES);

  // "ko-KR" -> "ko", "zh-Hant-HK" -> "zh-TW", "pt-PT" -> "pt-BR", unknown -> null.
  function resolve(tag) {
    const value = String(tag || "").trim().replace(/_/g, "-").toLowerCase();
    if (!value) return null;
    const [base] = value.split("-");
    if (base === "zh") return /-(?:hant|tw|hk|mo)\b/.test(value) ? "zh-TW" : "zh-CN";
    if (base === "pt") return "pt-BR";
    return LOCALES.includes(base) ? base : null;
  }

  function create(...tags) {
    const locale = tags.map(resolve).find(Boolean) || "en";
    const table = MESSAGES[locale], fallback = MESSAGES.en;
    let rules, numbers;
    try { rules = new Intl.PluralRules(locale); numbers = new Intl.NumberFormat(locale); }
    catch { rules = null; numbers = null; }
    function template(key, params) {
      let value = table[key] ?? fallback[key] ?? key;
      if (value && typeof value === "object") {
        const category = rules && Number.isFinite(params.n) ? rules.select(params.n) : "other";
        value = value[category] ?? value.other;
      }
      return value;
    }
    const show = value => typeof value === "number" && numbers ? numbers.format(value) : String(value);
    // Template split into text and {name, value} placeholders, so callers can style values.
    function parts(key, params = {}) {
      return template(key, params).split(/(\{\w+\})/).filter(Boolean).map(piece => {
        const name = piece.match(/^\{(\w+)\}$/)?.[1];
        return name && name in params ? { name, value: show(params[name]) } : piece;
      });
    }
    function t(key, params = {}) {
      return parts(key, params).map(part => typeof part === "string" ? part : part.value).join("");
    }
    return { locale, t, parts, number: show };
  }

